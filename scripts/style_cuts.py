"""Style cuts for the opponent's clips: drop the stretches that make a kung-fu form look like a form instead of a fight.
The KungFuAthleteBot clips are solo routines. Between strikes they pause in a stance and pose with both arms overhead;
replayed in front of the R1 that reads as an opponent standing around. Cut (frame ranges into the clip after the tracker
cuts, before grounding):
  idle    >= 0.4 s where every hand and foot moves < 0.6 m/s (root drift removed, as the in-place opponent sees it)
  posing  >= 0.3 s with both hands >= 0.25 m above the torso
Writes r1gym/assets/motions/style_cuts.json (FightReplay applies it); the opponent's tracker is trained on the result."""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np, mujoco
from r1gym import opponent as O

IDLE_SPEED, IDLE_S, POSE_DZ, POSE_S = 0.6, 0.4, 0.25, 0.3

def ranges(clip, fps=50.0):
    z = np.load(O.ASSETS / "motions" / f"{clip}.npz"); q = z["qpos"].astype(float)
    rep = O.FightReplay.__new__(O.FightReplay); rep.clip = clip; rep.raw = q.copy()
    q, _ = O.clean_clip(rep._retarget(q), fps); q = O.apply_cuts(q, fps, O._cuts().get(clip, []))
    qi = q.copy(); qi[:, :2] -= O._lowpass(q[:, :2], int(round(fps)))                 # in place, as _canon does
    r = O._sub("r1"); d = mujoco.MjData(r); ee = [r.body(n).id for n in ("left_wrist_roll_link", "right_wrist_roll_link", "left_ankle_roll_link", "right_ankle_roll_link")]
    tor = r.body("torso_link").id; P = np.zeros((len(q), 4, 3)); T = np.zeros((len(q), 3))
    for t in range(len(q)):
        d.qpos[:] = qi[t]; mujoco.mj_kinematics(r, d); P[t] = d.xpos[ee]; T[t] = d.xpos[tor]
    speed = np.linalg.norm(np.gradient(P, 1 / fps, axis=0), axis=2).max(1)
    idle = np.convolve(speed < IDLE_SPEED, np.ones(5) / 5, "same") > 0.99            # 0.1 s smoothing
    pose = ((P[:, :2, 2] - T[:, None, 2]) > POSE_DZ).all(1)
    out = [(a, b, "idle") for a, b in O._runs(idle) if b - a >= IDLE_S * fps] + [(a, b, "posing") for a, b in O._runs(pose) if b - a >= POSE_S * fps]
    return sorted(out), len(q)

if __name__ == "__main__":
    cuts, about = {}, {}
    for clip in O.list_clips():
        rr, n = ranges(clip); cuts[clip] = [[int(a), int(b)] for a, b, _ in rr]
        about[clip] = f"{n} frames; cut " + ", ".join(f"{k} {a}-{b}" for a, b, k in rr) if rr else f"{n} frames; nothing cut"
        print(clip, about[clip])
    out = O.ASSETS / "motions" / "style_cuts.json"
    json.dump({"about": __doc__.split("\n")[0] + " Generated by scripts/style_cuts.py.", "rule": dict(idle_speed_mps=IDLE_SPEED, idle_s=IDLE_S, pose_hands_above_torso_m=POSE_DZ, pose_s=POSE_S),
               "per_clip": about, "cuts": cuts}, open(out, "w"), indent=1)
    print("wrote", out)
